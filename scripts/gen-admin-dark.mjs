// ════════════════════════════════════════════════════════════════════════
//  BALKOUN · the admin panel's night mode, generated (2026-10-16)
//
//  The panel's stylesheet has a few hundred rules with fixed light colours.
//  Rather than hand-write a night twin for each, this reads the stylesheet in
//  index.html and writes, between the ADM-DARK markers, a night version of every
//  rule that sets a colour, under `html.adm-dark` (set by admin.js while the
//  panel is open and night mode is on). Light surfaces become dark ones of the
//  same hue, dark text becomes light, light borders become dark lines, and the
//  navy fills of primary controls become gold with dark text.
//  Re-run after changing the panel's styles:  node scripts/gen-admin-dark.mjs
// ════════════════════════════════════════════════════════════════════════
import fs from "fs";

const FILE = "index.html";
const START = "/* ADM-DARK:START (generated by scripts/gen-admin-dark.mjs — do not edit by hand) */";
const END = "/* ADM-DARK:END */";

let html = fs.readFileSync(FILE, "utf8");
// the main stylesheet = the first <style> block; drop an earlier generated block before reading it
const s0 = html.indexOf("<style>"), s1 = html.indexOf("</style>", s0);
let css = html.slice(s0 + 7, s1);
const gi = css.indexOf(START);
if (gi > -1) css = css.slice(0, gi) + css.slice(css.indexOf(END) + END.length);
css = css.replace(/\/\*[\s\S]*?\*\//g, "");

// ── colours ──
const hex2rgb = (h) => { h = h.replace("#", ""); if (h.length === 3 || h.length === 4) h = h.split("").map((c) => c + c).join("");
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16), h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1]; };
const rgb2hsl = ([r, g, b]) => { r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b); let h = 0, s = 0; const l = (mx + mn) / 2;
  if (mx !== mn) { const d = mx - mn; s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn); h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h /= 6; } return [h, s, l]; };
// h: a 0–1 fraction (from rgb2hsl) or whole degrees (the fixed dark hues)
const hsl = (h, s, l, a = 1) => `hsla(${Math.round(h > 1 ? h : h * 360)},${Math.round(s * 100)}%,${Math.round(l * 100)}%,${+a.toFixed(3)})`;
const parse = (c) => {
  c = c.trim().toLowerCase();
  if (c === "white" || c === "#fff" || c === "#ffffff") return [255, 255, 255, 1];
  if (c === "black") return [0, 0, 0, 1];
  if (/^#[0-9a-f]{3,8}$/.test(c)) return hex2rgb(c);
  const m = c.match(/^rgba?\(([^)]+)\)$/); if (m) { const p = m[1].split(/[\s,\/]+/).filter(Boolean).map(Number); return [p[0], p[1], p[2], p[3] == null ? 1 : p[3]]; }
  return null;
};
const NAVY = /^(#14213d|var\(--navy\))$/i;
function bg(c) {
  if (NAVY.test(c.trim())) return "var(--gold)";
  const v = parse(c); if (!v) return null;
  const [h, s, l] = rgb2hsl(v), a = v[3];
  if (a === 0) return null;
  if (l >= 0.86) {                                        // light surface → dark surface, tinted ones keep their hue
    if (s < 0.18) return hsl(222, 0.27, l >= 0.99 ? 0.13 : l >= 0.95 ? 0.155 : 0.18, a);
    return hsl(h, Math.min(s, 0.55) * 0.7, 0.17, a);
  }
  if (l >= 0.6) return hsl(h, s * 0.6, 0.26, a);           // mid-light fills
  if (l < 0.22 && s < 0.25) return hsl(222, 0.22, 0.22, a); // near-black fills (Polaris greys) → raised dark
  return null;                                            // saturated mid/dark fills stay as they are
}
function fg(c) {
  if (NAVY.test(c.trim())) return "#C9D6F2";
  const v = parse(c); if (!v) return null;
  const [h, s, l] = rgb2hsl(v);
  if (l <= 0.3) return s < 0.25 ? hsl(220, 0.2, 0.9, v[3]) : hsl(h, Math.min(1, s), 0.78, v[3]);
  if (l <= 0.5) return s < 0.25 ? hsl(220, 0.12, 0.7, v[3]) : hsl(h, Math.min(1, s), 0.72, v[3]);
  return null;                                            // light text stays light
}
function line(c) { const v = parse(c); if (!v) return null; const l = rgb2hsl(v)[2]; return l >= 0.7 ? hsl(222, 0.2, 0.25, v[3]) : null; }
const COLOR_TOKEN = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b|var\(--navy\)/g;

// ── a tiny CSS reader: rules and one level of @media/@supports ──
function blocks(src) {
  const out = []; let i = 0;
  while (i < src.length) {
    const ob = src.indexOf("{", i); if (ob < 0) break;
    const head = src.slice(i, ob).trim();
    let depth = 1, j = ob + 1;
    while (j < src.length && depth) { if (src[j] === "{") depth++; else if (src[j] === "}") depth--; j++; }
    const body = src.slice(ob + 1, j - 1);
    if (head.startsWith("@media") || head.startsWith("@supports")) out.push({ at: head, rules: blocks(body) });
    else if (!head.startsWith("@")) out.push({ sel: head, body });
    i = j;
  }
  return out;
}
function darkDecls(body) {
  const out = []; let navyBg = false;
  for (const d of body.split(";")) {
    const k = d.indexOf(":"); if (k < 0) continue;
    const prop = d.slice(0, k).trim().toLowerCase(), val = d.slice(k + 1).trim(); if (!val) continue;
    const imp = /!important/.test(val) ? " !important" : "", v = val.replace(/\s*!important/, "");
    if (prop === "background" || prop === "background-color") {
      if (/url\(/.test(v)) continue;
      if (/gradient\(/.test(v)) { const nv = v.replace(COLOR_TOKEN, (c) => bg(c) || c); if (nv !== v) out.push(`${prop}:${nv}${imp}`); continue; }
      const toks = v.match(COLOR_TOKEN); if (!toks || toks.length !== 1) continue;
      if (NAVY.test(toks[0])) navyBg = true;
      const m = bg(toks[0]); if (m) out.push(`${prop}:${v.replace(toks[0], m)}${imp}`);
    } else if (prop === "color" || prop === "fill" || prop === "stroke" || prop === "caret-color") {
      const m = fg(v); if (m) out.push(`${prop}:${m}${imp}`);
    } else if (/^border(-(top|bottom|left|right|inline-start|inline-end|block-start|block-end))?(-color)?$/.test(prop) || prop === "outline" || prop === "outline-color") {
      const nv = v.replace(COLOR_TOKEN, (c) => (NAVY.test(c) ? "var(--gold)" : line(c)) || c); if (nv !== v) out.push(`${prop}:${nv}${imp}`);
    }
  }
  // a navy fill with white text (primary buttons, the selected tab) becomes gold with dark text
  if (navyBg && /(^|;)\s*color\s*:\s*(#fff\b|#ffffff\b|white\b)/i.test(body)) out.push("color:#1A1206");
  return out;
}
// only rules the panel can actually hit: their classes appear in admin.js (or they are .adm rules); the public
// site's own classes are skipped so visitors don't download night rules they never use
// part of the panel (the dashboard cards, the stats charts) is drawn by code inside index.html, so its scripts count too
const ADMIN_SRC = fs.readFileSync("admin.js", "utf8") + (html.match(/<script>[\s\S]*?<\/script>/g) || []).join("");
const usedByPanel = (sel) => /(^|[\s,>+~(])\.adm\b|admdm/.test(sel) || (sel.match(/\.[a-zA-Z][\w-]*/g) || []).some((c) => ADMIN_SRC.includes(c.slice(1)));
const scope = (sel) => sel.split(",").map((x) => x.trim()).filter(Boolean).flatMap((x) => {
  if (/^(html|body|:root)\b/.test(x)) return [];
  if (/^\.adm\b|^\[dir=rtl\] \.adm\b/.test(x)) return [`html.adm-dark ${x.replace(/^\[dir=rtl\] /, "")}`];
  return [`html.adm-dark .adm ${x}`, `html.adm-dark .admdm-ov ${x}`];
}).join(",");

let n = 0;
function emit(list) {
  let s = "";
  for (const b of list) {
    if (b.at) { const inner = emit(b.rules); if (inner) s += `${b.at}{${inner}}`; continue; }
    const d = darkDecls(b.body); if (!d.length) continue;
    if (!usedByPanel(b.sel)) continue;
    const sel = scope(b.sel); if (!sel) continue;
    s += `${sel}{${d.join(";")}}\n`; n++;
  }
  return s;
}
const out = emit(blocks(css));
const block = `${START}\n${out}${END}`;
let full = html.slice(s0 + 7, s1);
if (full.includes(START)) full = full.slice(0, full.indexOf(START)) + block + full.slice(full.indexOf(END) + END.length);
else full = full + "\n" + block + "\n";
html = html.slice(0, s0 + 7) + full + html.slice(s1);
fs.writeFileSync(FILE, html);
console.log(`admin night mode: ${n} rules written (${(block.length / 1024).toFixed(0)} KB)`);
